#include "libft.h"

int	ft_read_int(const char **fmt)
{
	int	i;

	i = 0;
	while (ft_isdigit(**fmt))
	{
		i *= 10;
		i += **fmt - '0';
		(*fmt)++;
	}
	return (i);
}
