#include "../char/ft_char.h"

#define BASE 10

int	ft_read_int(const char **fmt)
{
	int	i;

	i = 0;
	while (ft_isdigit(**fmt))
	{
		i *= BASE;
		i += **fmt - '0';
		(*fmt)++;
	}
	return (i);
}
